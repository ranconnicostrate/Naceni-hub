import React, { useEffect, useState } from 'react';
import {
  AlertTriangle,
  ArrowRightLeft,
  CheckCircle2,
  Package,
  Plus,
  RefreshCw,
  Warehouse as WarehouseIcon,
  X,
} from 'lucide-react';
import { useAuth } from '../../context/AuthContext.tsx';
import { apiFetch, formatRwf } from '../../services/api.ts';

interface InventoryItem {
  id: number;
  sku: string;
  name: string;
  categoryName: string | null;
  supplierId: number | null;
  supplierName: string | null;
  unitOfMeasure: string;
  wholesalePriceRwf: number;
  availableStock: number;
  minStockLevel: number;
  reorderPoint: number;
  reorderQuantity: number;
  batchNumber: string | null;
}

interface PurchaseOrder {
  id: number;
  poNumber: string;
  supplierName: string;
  status: string;
  totalCostRwf: number;
  isAutoGenerated: boolean;
  notes: string;
  createdAt: string;
  items: {
    id: number;
    productName: string;
    sku: string;
    quantityOrdered: number;
    unitCostRwf: number;
    lineTotalRwf: number;
  }[];
}

export const InventoryProcurementTab: React.FC<{
  mode: 'inventory' | 'procurement';
}> = ({ mode }) => {
  const { socket, user } = useAuth();
  const [summary, setSummary] = useState({
    totalStockUnits: 0,
    lowStockCount: 0,
    outOfStockCount: 0,
    inventoryValueRwf: 0,
  });
  const [items, setItems] = useState<InventoryItem[]>([]);
  const [warehouses, setWarehouses] = useState<{ id: number; name: string; code: string }[]>([]);
  const [movements, setMovements] = useState<any[]>([]);
  const [pos, setPos] = useState<PurchaseOrder[]>([]);
  const [recommendations, setRecommendations] = useState<any[]>([]);
  const [suppliers, setSuppliers] = useState<{ id: number; name: string }[]>([]);
  const [showAdjustModal, setShowAdjustModal] = useState(false);
  const [showPoModal, setShowPoModal] = useState(false);
  const [adjForm, setAdjForm] = useState({
    productId: 0,
    warehouseId: 1,
    targetWarehouseId: 2,
    type: 'INCOMING' as 'INCOMING' | 'OUTGOING' | 'ADJUSTMENT' | 'TRANSFER',
    quantity: 10,
    batchCode: 'BATCH-2026-Q4',
    notes: '',
  });
  const [poForm, setPoForm] = useState({
    supplierId: 1,
    productId: 0,
    quantityOrdered: 25,
    unitCostRwf: 65000,
    notes: '',
  });
  const [message, setMessage] = useState('');

  const loadAll = async () => {
    try {
      const [invRes, movRes, supRes] = await Promise.all([
        apiFetch<any>('/api/inventory'),
        apiFetch<any>('/api/stock-movements'),
        apiFetch<any>('/api/suppliers'),
      ]);
      setSummary(invRes.summary);
      setItems(invRes.items);
      setWarehouses(invRes.warehouses);
      setMovements(movRes.movements);
      setSuppliers(supRes.suppliers);

      if (invRes.items.length > 0 && adjForm.productId === 0) {
        setAdjForm((prev) => ({ ...prev, productId: invRes.items[0].id }));
        setPoForm((prev) => ({
          ...prev,
          productId: invRes.items[0].id,
          supplierId: supRes.suppliers[0]?.id || 1,
        }));
      }

      if (['SUPER_ADMIN', 'INVENTORY_MANAGER', 'WAREHOUSE_STAFF'].includes(user?.role || '')) {
        const poRes = await apiFetch<any>('/api/procurement/purchase-orders');
        setPos(poRes.purchaseOrders);
      }
      if (['SUPER_ADMIN', 'INVENTORY_MANAGER'].includes(user?.role || '')) {
        const recRes = await apiFetch<any>('/api/reorders/recommendations');
        setRecommendations(recRes.recommendations);
      }
    } catch (err) {
      console.error(err);
    }
  };

  useEffect(() => {
    void loadAll();
  }, []);

  useEffect(() => {
    if (!socket) return;
    const refresh = () => void loadAll();
    socket.on('inventory:updated', refresh);
    socket.on('procurement:updated', refresh);
    return () => {
      socket.off('inventory:updated', refresh);
      socket.off('procurement:updated', refresh);
    };
  }, [socket]);

  const handleAdjustSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    setMessage('');
    try {
      await apiFetch('/api/inventory/adjust', {
        method: 'POST',
        body: JSON.stringify(adjForm),
      });
      setShowAdjustModal(false);
      setMessage('Stock movement recorded and real-time inventory updated.');
      await loadAll();
    } catch (err: any) {
      setMessage(err?.message || 'Stock adjustment failed.');
    }
  };

  const handleTriggerReorderCheck = async () => {
    try {
      const res = await apiFetch<{ generatedCount: number }>(
        '/api/reorders/trigger-check',
        { method: 'POST' }
      );
      setMessage(
        `Automated reorder scan complete: ${res.generatedCount} new draft PO(s) created.`
      );
      await loadAll();
    } catch (err: any) {
      setMessage(err?.message || 'Reorder scan failed.');
    }
  };

  const handlePoStatus = async (poId: number, status: string) => {
    try {
      await apiFetch(`/api/procurement/purchase-orders/${poId}/status`, {
        method: 'PATCH',
        body: JSON.stringify({ status }),
      });
      setMessage(`Purchase order updated to ${status}.`);
      await loadAll();
    } catch (err: any) {
      setMessage(err?.message || 'Failed to update purchase order.');
    }
  };

  const handleCreatePo = async (e: React.FormEvent) => {
    e.preventDefault();
    try {
      await apiFetch('/api/procurement/purchase-orders', {
        method: 'POST',
        body: JSON.stringify({
          supplierId: poForm.supplierId,
          notes: poForm.notes,
          items: [
            {
              productId: poForm.productId,
              quantityOrdered: poForm.quantityOrdered,
              unitCostRwf: poForm.unitCostRwf,
            },
          ],
        }),
      });
      setShowPoModal(false);
      setMessage('Purchase order created and submitted for approval.');
      await loadAll();
    } catch (err: any) {
      setMessage(err?.message || 'Failed to create PO.');
    }
  };

  return (
    <div className="space-y-6">
      <div className="flex flex-wrap items-center justify-between gap-4">
        <div>
          <h1 className="font-display text-2xl font-bold text-[#0B1F3A]">
            {mode === 'inventory'
              ? 'Inventory Management'
              : 'Procurement & Automated Reordering'}
          </h1>
          <p className="text-sm text-slate-500">
            {mode === 'inventory'
              ? 'Real-time stock monitoring across Kigali & Northern warehouses'
              : 'Automated replenishment rules, supplier purchase orders & receiving'}
          </p>
        </div>
        <div className="flex flex-wrap gap-2">
          {mode === 'inventory' ? (
            <button
              type="button"
              onClick={() => setShowAdjustModal(true)}
              className="inline-flex items-center gap-1.5 rounded-lg bg-[#1D4ED8] px-4 py-2.5 text-xs font-bold text-white hover:bg-[#1E40AF]"
            >
              <Plus className="h-4 w-4" />
              Add / Adjust Stock
            </button>
          ) : (
            <>
              <button
                type="button"
                onClick={handleTriggerReorderCheck}
                className="inline-flex items-center gap-1.5 rounded-lg border border-slate-300 bg-white px-4 py-2.5 text-xs font-bold text-[#0B1F3A] hover:bg-slate-50"
              >
                <RefreshCw className="h-4 w-4 text-[#F97316]" />
                Run Auto-Reorder Scan
              </button>
              <button
                type="button"
                onClick={() => setShowPoModal(true)}
                className="inline-flex items-center gap-1.5 rounded-lg bg-[#0B1F3A] px-4 py-2.5 text-xs font-bold text-white hover:bg-[#13325C]"
              >
                <Plus className="h-4 w-4" />
                New Purchase Order
              </button>
            </>
          )}
        </div>
      </div>

      {message && (
        <div className="rounded-lg border border-emerald-200 bg-emerald-50 px-4 py-2.5 text-xs font-semibold text-emerald-800">
          {message}
        </div>
      )}

      {mode === 'inventory' && (
        <>
          {/* 4 Summary Cards matching bottom-center mockup */}
          <div className="grid gap-4 sm:grid-cols-2 lg:grid-cols-4">
            <div className="rounded-xl border border-slate-200 bg-white p-4">
              <div className="flex items-center gap-2 text-xs font-semibold text-slate-500">
                <Package className="h-4 w-4 text-[#1D4ED8]" />
                Total Stock
              </div>
              <div className="mt-2 font-mono text-2xl font-bold text-[#0B1F3A] tabular-nums">
                {summary.totalStockUnits.toLocaleString()}
              </div>
            </div>
            <div className="rounded-xl border border-slate-200 bg-white p-4">
              <div className="flex items-center gap-2 text-xs font-semibold text-slate-500">
                <AlertTriangle className="h-4 w-4 text-amber-500" />
                Low Stock
              </div>
              <div className="mt-2 font-mono text-2xl font-bold text-amber-600 tabular-nums">
                {summary.lowStockCount}
              </div>
            </div>
            <div className="rounded-xl border border-slate-200 bg-white p-4">
              <div className="flex items-center gap-2 text-xs font-semibold text-slate-500">
                <AlertTriangle className="h-4 w-4 text-red-600" />
                Out of Stock
              </div>
              <div className="mt-2 font-mono text-2xl font-bold text-red-600 tabular-nums">
                {summary.outOfStockCount}
              </div>
            </div>
            <div className="rounded-xl border border-slate-200 bg-white p-4">
              <div className="flex items-center gap-2 text-xs font-semibold text-slate-500">
                <WarehouseIcon className="h-4 w-4 text-emerald-600" />
                Inventory Value
              </div>
              <div className="mt-2 font-mono text-xl font-bold text-emerald-700 tabular-nums">
                {formatRwf(summary.inventoryValueRwf)}
              </div>
            </div>
          </div>

          {/* Live Inventory Table */}
          <div className="rounded-xl border border-slate-200 bg-white p-5">
            <h2 className="font-display text-base font-bold text-[#0B1F3A]">
              Live Product Stock Levels
            </h2>
            <div className="mt-3 overflow-x-auto">
              <table className="w-full text-left text-xs">
                <thead>
                  <tr className="border-b border-slate-200 text-slate-500">
                    <th className="py-2.5">Product</th>
                    <th className="py-2.5">SKU</th>
                    <th className="py-2.5 text-right">Stock</th>
                    <th className="py-2.5 text-right">Min Stock</th>
                    <th className="py-2.5">Batch</th>
                    <th className="py-2.5">Status</th>
                    <th className="py-2.5 text-right">Action</th>
                  </tr>
                </thead>
                <tbody className="divide-y divide-slate-100">
                  {items.map((item) => {
                    const status =
                      item.availableStock <= 0
                        ? 'Out of Stock'
                        : item.availableStock <= item.minStockLevel
                          ? 'Low Stock'
                          : 'In Stock';
                    return (
                      <tr key={item.id} className="hover:bg-slate-50">
                        <td className="py-3 font-semibold text-slate-900">
                          {item.name}
                        </td>
                        <td className="py-3 font-mono text-slate-500">
                          {item.sku}
                        </td>
                        <td className="py-3 text-right font-mono font-bold text-[#0B1F3A] tabular-nums">
                          {item.availableStock}
                        </td>
                        <td className="py-3 text-right font-mono text-slate-500 tabular-nums">
                          {item.minStockLevel}
                        </td>
                        <td className="py-3 font-mono text-slate-500">
                          {item.batchNumber || '-'}
                        </td>
                        <td className="py-3">
                          <span
                            className={`font-semibold ${
                              status === 'Out of Stock'
                                ? 'text-red-600'
                                : status === 'Low Stock'
                                  ? 'text-amber-600'
                                  : 'text-emerald-700'
                            }`}
                          >
                            {status}
                          </span>
                        </td>
                        <td className="py-3 text-right">
                          <button
                            type="button"
                            onClick={() => {
                              setAdjForm((prev) => ({
                                ...prev,
                                productId: item.id,
                                type: 'INCOMING',
                              }));
                              setShowAdjustModal(true);
                            }}
                            className="rounded-md border border-slate-200 px-2.5 py-1 font-semibold text-[#0B1F3A] hover:bg-slate-100"
                          >
                            Restock
                          </button>
                        </td>
                      </tr>
                    );
                  })}
                </tbody>
              </table>
            </div>
          </div>

          {/* Stock Movement History */}
          <div className="rounded-xl border border-slate-200 bg-white p-5">
            <h2 className="flex items-center gap-2 font-display text-base font-bold text-[#0B1F3A]">
              <ArrowRightLeft className="h-4 w-4 text-[#F97316]" />
              Recent Stock Movements
            </h2>
            <div className="mt-3 overflow-x-auto">
              <table className="w-full text-left text-xs">
                <thead>
                  <tr className="border-b border-slate-200 text-slate-500">
                    <th className="py-2">Date</th>
                    <th className="py-2">SKU</th>
                    <th className="py-2">Type</th>
                    <th className="py-2 text-right">Delta</th>
                    <th className="py-2 text-right">New Stock</th>
                    <th className="py-2">Reference / Notes</th>
                  </tr>
                </thead>
                <tbody className="divide-y divide-slate-100">
                  {movements.slice(0, 15).map((m) => (
                    <tr key={m.id}>
                      <td className="py-2.5 text-slate-500">
                        {new Date(m.createdAt).toLocaleString()}
                      </td>
                      <td className="py-2.5 font-mono font-semibold text-[#0B1F3A]">
                        {m.sku}
                      </td>
                      <td className="py-2.5 font-semibold">{m.type}</td>
                      <td
                        className={`py-2.5 text-right font-mono font-bold tabular-nums ${
                          m.quantityDelta >= 0
                            ? 'text-emerald-700'
                            : 'text-red-600'
                        }`}
                      >
                        {m.quantityDelta >= 0 ? `+${m.quantityDelta}` : m.quantityDelta}
                      </td>
                      <td className="py-2.5 text-right font-mono tabular-nums">
                        {m.newStock}
                      </td>
                      <td className="py-2.5 text-slate-600">
                        {m.referenceId ? `${m.referenceId} · ` : ''}
                        {m.notes}
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          </div>
        </>
      )}

      {mode === 'procurement' && (
        <>
          {/* Automated Reorder Recommendations */}
          <div className="rounded-xl border border-slate-200 bg-white p-5">
            <h2 className="font-display text-base font-bold text-[#0B1F3A]">
              Automated Reorder Recommendations ({recommendations.length})
            </h2>
            {recommendations.length === 0 ? (
              <p className="mt-2 text-xs text-slate-500">
                All SKUs are above configured reorder points.
              </p>
            ) : (
              <div className="mt-3 overflow-x-auto">
                <table className="w-full text-left text-xs">
                  <thead>
                    <tr className="border-b border-slate-200 text-slate-500">
                      <th className="py-2">SKU</th>
                      <th className="py-2">Product</th>
                      <th className="py-2 text-right">Stock</th>
                      <th className="py-2 text-right">Reorder Point</th>
                      <th className="py-2 text-right">Suggested Qty</th>
                      <th className="py-2">Preferred Supplier</th>
                    </tr>
                  </thead>
                  <tbody className="divide-y divide-slate-100">
                    {recommendations.map((rec) => (
                      <tr key={rec.productId}>
                        <td className="py-2.5 font-mono font-bold">{rec.sku}</td>
                        <td className="py-2.5 font-semibold">{rec.name}</td>
                        <td className="py-2.5 text-right font-mono font-bold text-red-600">
                          {rec.availableStock}
                        </td>
                        <td className="py-2.5 text-right font-mono">
                          {rec.reorderPoint}
                        </td>
                        <td className="py-2.5 text-right font-mono font-bold text-[#0B1F3A]">
                          {rec.reorderQuantity}
                        </td>
                        <td className="py-2.5 text-slate-600">
                          {rec.supplierName || 'Default'} ({rec.leadTimeDays || 4}d lead)
                        </td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            )}
          </div>

          {/* Supplier Purchase Orders */}
          <div className="rounded-xl border border-slate-200 bg-white p-5">
            <h2 className="font-display text-base font-bold text-[#0B1F3A]">
              Supplier Purchase Orders
            </h2>
            <div className="mt-3 overflow-x-auto">
              <table className="w-full text-left text-xs">
                <thead>
                  <tr className="border-b border-slate-200 text-slate-500">
                    <th className="py-2.5">PO #</th>
                    <th className="py-2.5">Supplier</th>
                    <th className="py-2.5">Items</th>
                    <th className="py-2.5">Status</th>
                    <th className="py-2.5 text-right">Total Cost</th>
                    <th className="py-2.5 text-right">Workflow Actions</th>
                  </tr>
                </thead>
                <tbody className="divide-y divide-slate-100">
                  {pos.map((po) => (
                    <tr key={po.id}>
                      <td className="py-3 font-mono font-bold text-[#0B1F3A]">
                        {po.poNumber}
                        {po.isAutoGenerated && (
                          <span className="ml-1.5 text-[10px] font-semibold text-[#F97316]">
                            Auto
                          </span>
                        )}
                      </td>
                      <td className="py-3 text-slate-700">{po.supplierName}</td>
                      <td className="py-3 text-slate-600">
                        {po.items
                          .map((i) => `${i.quantityOrdered}x ${i.sku}`)
                          .join(', ')}
                      </td>
                      <td className="py-3 font-semibold text-slate-800">
                        {po.status.replace(/_/g, ' ')}
                      </td>
                      <td className="py-3 text-right font-mono font-bold tabular-nums">
                        {formatRwf(po.totalCostRwf)}
                      </td>
                      <td className="py-3 text-right">
                        <div className="inline-flex gap-1.5">
                          {(po.status === 'DRAFT' ||
                            po.status === 'PENDING_APPROVAL') && (
                            <button
                              type="button"
                              onClick={() => handlePoStatus(po.id, 'APPROVED')}
                              className="rounded-md bg-[#0B1F3A] px-2.5 py-1 font-semibold text-white hover:bg-[#13325C]"
                            >
                              Approve PO
                            </button>
                          )}
                          {po.status === 'APPROVED' && (
                            <button
                              type="button"
                              onClick={() => handlePoStatus(po.id, 'ORDERED')}
                              className="rounded-md bg-[#1D4ED8] px-2.5 py-1 font-semibold text-white"
                            >
                              Mark Ordered
                            </button>
                          )}
                          {(po.status === 'APPROVED' ||
                            po.status === 'ORDERED') && (
                            <button
                              type="button"
                              onClick={() => handlePoStatus(po.id, 'RECEIVED')}
                              className="inline-flex items-center gap-1 rounded-md bg-emerald-600 px-2.5 py-1 font-semibold text-white hover:bg-emerald-700"
                            >
                              <CheckCircle2 className="h-3 w-3" />
                              Receive Goods
                            </button>
                          )}
                        </div>
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          </div>
        </>
      )}

      {/* Stock Adjustment Modal */}
      {showAdjustModal && (
        <div className="fixed inset-0 z-50 flex items-center justify-center bg-[#0B1F3A]/60 p-4">
          <div className="w-full max-w-md rounded-xl bg-white p-6 shadow-2xl">
            <div className="flex items-center justify-between pb-3">
              <h3 className="font-display text-lg font-bold text-[#0B1F3A]">
                Record Stock Movement
              </h3>
              <button
                type="button"
                onClick={() => setShowAdjustModal(false)}
                className="text-slate-400 hover:text-slate-700"
              >
                <X className="h-5 w-5" />
              </button>
            </div>
            <form onSubmit={handleAdjustSubmit} className="space-y-3 text-xs">
              <div>
                <label className="mb-1 block font-semibold">Product</label>
                <select
                  value={adjForm.productId}
                  onChange={(e) =>
                    setAdjForm({ ...adjForm, productId: Number(e.target.value) })
                  }
                  className="w-full rounded-lg border border-slate-300 px-3 py-2"
                >
                  {items.map((i) => (
                    <option key={i.id} value={i.id}>
                      {i.sku} — {i.name} (Stock: {i.availableStock})
                    </option>
                  ))}
                </select>
              </div>
              <div className="grid grid-cols-2 gap-3">
                <div>
                  <label className="mb-1 block font-semibold">Movement Type</label>
                  <select
                    value={adjForm.type}
                    onChange={(e) =>
                      setAdjForm({ ...adjForm, type: e.target.value as any })
                    }
                    className="w-full rounded-lg border border-slate-300 px-3 py-2"
                  >
                    <option value="INCOMING">Incoming Stock</option>
                    <option value="OUTGOING">Outgoing Stock</option>
                    <option value="ADJUSTMENT">Stock Audit Adjustment</option>
                    <option value="TRANSFER">Warehouse Transfer</option>
                  </select>
                </div>
                <div>
                  <label className="mb-1 block font-semibold">Quantity</label>
                  <input
                    type="number"
                    min={1}
                    required
                    value={adjForm.quantity}
                    onChange={(e) =>
                      setAdjForm({
                        ...adjForm,
                        quantity: Math.max(1, Number(e.target.value) || 1),
                      })
                    }
                    className="w-full rounded-lg border border-slate-300 px-3 py-2 font-mono"
                  />
                </div>
              </div>
              <div>
                <label className="mb-1 block font-semibold">Warehouse</label>
                <select
                  value={adjForm.warehouseId}
                  onChange={(e) =>
                    setAdjForm({ ...adjForm, warehouseId: Number(e.target.value) })
                  }
                  className="w-full rounded-lg border border-slate-300 px-3 py-2"
                >
                  {warehouses.map((w) => (
                    <option key={w.id} value={w.id}>
                      {w.name} ({w.code})
                    </option>
                  ))}
                </select>
              </div>
              {adjForm.type === 'TRANSFER' && (
                <div>
                  <label className="mb-1 block font-semibold">
                    Destination Warehouse
                  </label>
                  <select
                    value={adjForm.targetWarehouseId}
                    onChange={(e) =>
                      setAdjForm({
                        ...adjForm,
                        targetWarehouseId: Number(e.target.value),
                      })
                    }
                    className="w-full rounded-lg border border-slate-300 px-3 py-2"
                  >
                    {warehouses.map((w) => (
                      <option key={w.id} value={w.id}>
                        {w.name} ({w.code})
                      </option>
                    ))}
                  </select>
                </div>
              )}
              <div>
                <label className="mb-1 block font-semibold">Notes</label>
                <input
                  type="text"
                  value={adjForm.notes}
                  onChange={(e) =>
                    setAdjForm({ ...adjForm, notes: e.target.value })
                  }
                  placeholder="Supplier delivery note or audit reason"
                  className="w-full rounded-lg border border-slate-300 px-3 py-2"
                />
              </div>
              <button
                type="submit"
                className="w-full rounded-lg bg-[#0B1F3A] py-2.5 font-bold text-white hover:bg-[#13325C]"
              >
                Commit Stock Update
              </button>
            </form>
          </div>
        </div>
      )}

      {/* New Purchase Order Modal */}
      {showPoModal && (
        <div className="fixed inset-0 z-50 flex items-center justify-center bg-[#0B1F3A]/60 p-4">
          <div className="w-full max-w-md rounded-xl bg-white p-6 shadow-2xl">
            <div className="flex items-center justify-between pb-3">
              <h3 className="font-display text-lg font-bold text-[#0B1F3A]">
                Create Purchase Order
              </h3>
              <button
                type="button"
                onClick={() => setShowPoModal(false)}
                className="text-slate-400 hover:text-slate-700"
              >
                <X className="h-5 w-5" />
              </button>
            </div>
            <form onSubmit={handleCreatePo} className="space-y-3 text-xs">
              <div>
                <label className="mb-1 block font-semibold">Supplier</label>
                <select
                  value={poForm.supplierId}
                  onChange={(e) =>
                    setPoForm({ ...poForm, supplierId: Number(e.target.value) })
                  }
                  className="w-full rounded-lg border border-slate-300 px-3 py-2"
                >
                  {suppliers.map((s) => (
                    <option key={s.id} value={s.id}>
                      {s.name}
                    </option>
                  ))}
                </select>
              </div>
              <div>
                <label className="mb-1 block font-semibold">Product</label>
                <select
                  value={poForm.productId}
                  onChange={(e) =>
                    setPoForm({ ...poForm, productId: Number(e.target.value) })
                  }
                  className="w-full rounded-lg border border-slate-300 px-3 py-2"
                >
                  {items.map((i) => (
                    <option key={i.id} value={i.id}>
                      {i.sku} — {i.name}
                    </option>
                  ))}
                </select>
              </div>
              <div className="grid grid-cols-2 gap-3">
                <div>
                  <label className="mb-1 block font-semibold">Quantity</label>
                  <input
                    type="number"
                    min={1}
                    value={poForm.quantityOrdered}
                    onChange={(e) =>
                      setPoForm({
                        ...poForm,
                        quantityOrdered: Number(e.target.value) || 1,
                      })
                    }
                    className="w-full rounded-lg border border-slate-300 px-3 py-2 font-mono"
                  />
                </div>
                <div>
                  <label className="mb-1 block font-semibold">
                    Unit Cost (Rwf)
                  </label>
                  <input
                    type="number"
                    min={100}
                    value={poForm.unitCostRwf}
                    onChange={(e) =>
                      setPoForm({
                        ...poForm,
                        unitCostRwf: Number(e.target.value) || 100,
                      })
                    }
                    className="w-full rounded-lg border border-slate-300 px-3 py-2 font-mono"
                  />
                </div>
              </div>
              <div>
                <label className="mb-1 block font-semibold">Notes</label>
                <input
                  type="text"
                  value={poForm.notes}
                  onChange={(e) =>
                    setPoForm({ ...poForm, notes: e.target.value })
                  }
                  className="w-full rounded-lg border border-slate-300 px-3 py-2"
                />
              </div>
              <button
                type="submit"
                className="w-full rounded-lg bg-[#F97316] py-2.5 font-bold text-white hover:bg-[#EA580C]"
              >
                Create Purchase Order
              </button>
            </form>
          </div>
        </div>
      )}
    </div>
  );
};
