import { and, eq, inArray } from 'drizzle-orm';
import { db } from '../../db/index.ts';
import {
  products,
  purchaseOrderItems,
  purchaseOrders,
  reorderRules,
  suppliers,
} from '../../db/schema.ts';
import { createNotification, emitRealtimeEvent } from './audit.ts';

export async function evaluateReorderForProduct(
  productId: number,
  actorId?: number | null
) {
  try {
    const [product] = await db
      .select()
      .from(products)
      .where(eq(products.id, productId))
      .limit(1);
    if (!product) return null;

    const [rule] = await db
      .select()
      .from(reorderRules)
      .where(eq(reorderRules.productId, productId))
      .limit(1);

    const reorderPoint = rule?.reorderPoint ?? product.reorderPoint;
    const reorderQty = rule?.reorderQuantity ?? product.reorderQuantity;
    const isActiveRule = rule ? rule.isActive : true;

    if (!isActiveRule || product.availableStock > reorderPoint) {
      return null;
    }

    const alertType = product.availableStock <= 0 ? 'OUT OF STOCK' : 'LOW STOCK';
    await createNotification({
      targetRole: 'INVENTORY_MANAGER',
      type: 'LOW_STOCK',
      title: `${alertType}: ${product.name}`,
      message: `SKU ${product.sku} has ${product.availableStock} ${product.unitOfMeasure}(s) remaining (Reorder point: ${reorderPoint}).`,
      linkView: 'inventory',
    });

    const supplierId = rule?.supplierId ?? product.supplierId;
    if (!supplierId) return null;

    const autoDraft = rule ? rule.autoDraftPo : true;
    if (!autoDraft) return null;

    // Avoid duplicate draft/pending/approved POs for the same product
    const openPos = await db
      .select({ poId: purchaseOrders.id })
      .from(purchaseOrders)
      .innerJoin(
        purchaseOrderItems,
        eq(purchaseOrderItems.purchaseOrderId, purchaseOrders.id)
      )
      .where(
        and(
          eq(purchaseOrderItems.productId, productId),
          inArray(purchaseOrders.status, ['DRAFT', 'PENDING_APPROVAL', 'APPROVED', 'ORDERED'])
        )
      )
      .limit(1);

    if (openPos.length > 0) return null;

    const [supplier] = await db
      .select()
      .from(suppliers)
      .where(eq(suppliers.id, supplierId))
      .limit(1);

    const unitCost = Math.round(product.wholesalePriceRwf * 0.78);
    const totalCost = unitCost * reorderQty;
    const poNumber = `PO-${new Date().getFullYear()}-${Math.floor(10000 + Math.random() * 89999)}`;
    const expectedDate = new Date();
    expectedDate.setDate(
      expectedDate.getDate() + (rule?.leadTimeDays ?? supplier?.leadTimeDays ?? 5)
    );

    const [createdPo] = await db
      .insert(purchaseOrders)
      .values({
        poNumber,
        supplierId,
        status: 'DRAFT',
        totalCostRwf: totalCost,
        expectedDeliveryDate: expectedDate,
        notes: `Auto-generated draft PO triggered when ${product.sku} reached ${product.availableStock} units.`,
        isAutoGenerated: true,
        createdById: actorId ?? null,
      })
      .returning();

    await db.insert(purchaseOrderItems).values({
      purchaseOrderId: createdPo.id,
      productId: product.id,
      quantityOrdered: reorderQty,
      quantityReceived: 0,
      unitCostRwf: unitCost,
      lineTotalRwf: totalCost,
    });

    await createNotification({
      targetRole: 'SUPER_ADMIN',
      type: 'REORDER',
      title: `Draft PO Created (${poNumber})`,
      message: `Automated reorder recommendation drafted for ${reorderQty}x ${product.name} pending manager approval.`,
      linkView: 'procurement',
    });

    emitRealtimeEvent('procurement:updated', { purchaseOrderId: createdPo.id });
    return createdPo;
  } catch (err) {
    console.error('Reorder evaluation failed:', err);
    return null;
  }
}
